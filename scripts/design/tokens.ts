import { readFileSync, writeFileSync } from "node:fs"
import { format, resolveConfig } from "prettier"
import { FIGMA, type FigmaExport } from "../../src/shared/domain/design/tokens"
import { themeCss } from "./css-theme"
import { variablesCss } from "./css-vars"
import { FIGMA_EXPORT_SCRIPT } from "./figma-export"

/**
 * Writes src/styles/generated from the Figma export.
 *   pnpm design:tokens                       regenerate the CSS
 *   pnpm design:tokens --check               fail when the CSS is not what the export gives
 *   pnpm design:tokens --from-figma <file>   take a fresh export, then regenerate
 *   pnpm design:tokens --export-script       print the script to run in Figma
 */
const EXPORT = "src/shared/domain/design/figma-export.json"
const HEADER = `/* Generated by scripts/design/tokens.ts from ${EXPORT}. Do not edit. */\n`

export async function generate(source: FigmaExport): Promise<Record<string, string>> {
  const files = {
    "src/styles/generated/variables.css": HEADER + variablesCss(source),
    "src/styles/generated/theme.css": HEADER + themeCss(source),
  }
  const formatted = await Promise.all(
    Object.entries(files).map(async ([path, css]) => [
      path,
      await format(css, { ...(await resolveConfig(path)), filepath: path }),
    ]),
  )
  return Object.fromEntries(formatted) as Record<string, string>
}

async function main(args: readonly string[]) {
  if (args.includes("--export-script")) return console.log(FIGMA_EXPORT_SCRIPT.trim())
  let source = FIGMA
  const from = args[args.indexOf("--from-figma") + 1]
  if (args.includes("--from-figma")) {
    if (!from) throw new Error("--from-figma needs the exported JSON file")
    source = JSON.parse(readFileSync(from, "utf8")) as FigmaExport
    await generate(source)
    writeFileSync(
      EXPORT,
      await format(JSON.stringify(source), { ...(await resolveConfig(EXPORT)), filepath: EXPORT }),
    )
  }
  const files = await generate(source)
  const check = args.includes("--check")
  const stale = Object.entries(files).filter(([path, css]) => {
    try {
      return readFileSync(path, "utf8") !== css
    } catch {
      return true
    }
  })
  if (check) {
    for (const [path] of stale) console.error(`${path} is stale: run pnpm design:tokens`)
    if (stale.length) process.exit(1)
    return console.log(`design tokens: ${Object.keys(files).length} files current`)
  }
  for (const [path, css] of stale) writeFileSync(path, css)
  console.log(`design tokens: wrote ${stale.length} of ${Object.keys(files).length} files`)
}

if (process.argv[1]?.endsWith("tokens.ts")) await main(process.argv.slice(2))
